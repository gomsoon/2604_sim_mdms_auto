def localized_url(target_locale: str) -> str:
    normalized_locale = normalize_locale(target_locale) or DEFAULT_LOCALE
    if request.endpoint is None:
        return request.path

    values = dict(request.view_args or {})
    values.update(request.args.to_dict(flat=True))
    values["lang"] = normalized_locale
    return url_for(request.endpoint, **values)


def register_i18n(app: Flask) -> None:
    @app.before_request
    def assign_locale() -> None:
        g.locale = detect_locale()

    @app.after_request
    def persist_locale(response):
        if "lang" in request.args:
            response.set_cookie(
                LOCALE_COOKIE_NAME,
                normalize_locale(request.args.get("lang")) or DEFAULT_LOCALE,
                samesite="Lax",
            )
        return response

    @app.context_processor
    def inject_i18n_helpers() -> dict[str, object]:
        return {
            "current_locale": get_locale(),
            "supported_locales": SUPPORTED_LOCALES,
            "localized_url": localized_url,
            "t": translate,
            "t_or": translate_or,
            "t_ingest_error": translate_ingest_error,
            "t_master_data_error": translate_master_data_error,
            "t_adapter_error": translate_adapter_error,
            "t_hes_system_error": translate_hes_system_error,
            "t_operational_alert_error": translate_operational_alert_error,
            "t_vee_exception_error": translate_vee_exception_error,
            "t_reprocess_result": translate_reprocess_result,
            "t_reprocess_error": translate_reprocess_error,
            "t_visibility_error": translate_visibility_error,
            "t_event_title": translate_operational_event_title,
            "t_event_message": translate_operational_event_message,
        }
